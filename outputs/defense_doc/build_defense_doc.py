def build():
    slides = sorted(SLIDES_DIR.glob("*.PNG"), key=slide_number)
    if len(slides) != len(speech):
        raise RuntimeError(f"Expected {len(speech)} slide images, found {len(slides)}")

    doc = Document()
    section = doc.sections[0]
    section.page_width = Mm(210)
    section.page_height = Mm(297)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)
    section.left_margin = Mm(30)
    section.right_margin = Mm(15)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Times New Roman"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    normal.font.size = Pt(10)

    table = doc.add_table(rows=len(slides), cols=2)
    table.style = "Table Grid"
    table.autofit = False

    # A4 usable width with margins 30 mm + 15 mm: 165 mm = about 9354 DXA.
    slide_col_dxa = 5200
    text_col_dxa = 4150

    for row_idx, row in enumerate(table.rows):
        row.height = None
        slide_cell = row.cells[0]
        text_cell = row.cells[1]
        for cell, width in ((slide_cell, slide_col_dxa), (text_cell, text_col_dxa)):
            set_cell_width(cell, width)
            set_cell_margins(cell)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER

        add_slide_image(slide_cell, slides[row_idx])
        add_text(text_cell, speech[row_idx])

    doc.save(OUT)
    print(OUT)


if __name__ == "__main__":
    build()
