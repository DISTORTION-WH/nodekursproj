def element_text(el):
    return "".join(
        t.text for t in el.iter()
        if t.tag.rsplit("}", 1)[-1] == "t" and t.text
    )


def paragraph_by_prefix(doc, prefix):
    for p in doc.paragraphs:
        if p.text.strip().startswith(prefix):
            return p
    raise ValueError(f"Paragraph not found: {prefix!r}")


def clear_paragraph(p):
    p._p.clear_content()


def set_paragraph(p, text, bold=False):
    clear_paragraph(p)
    run = p.add_run(text)
    run.bold = bold
    return p


def replace_paragraph(doc, prefix, text, bold=True):
    return set_paragraph(paragraph_by_prefix(doc, prefix), text, bold)


def replace_text(doc, old, new, bold=True):
    for p in doc.paragraphs:
        if p.text.strip() == old:
            set_paragraph(p, new, bold)
            return p
    raise ValueError(f"Exact paragraph not found: {old!r}")


def bold_paragraph(p):
    for run in p.runs:
        run.bold = True


def set_cell(cell, text, bold=False, size=None):
    for p in cell.paragraphs:
        clear_paragraph(p)
    p = cell.paragraphs[0]
    run = p.add_run(text)
    run.bold = bold
    if size is not None:
        run.font.size = Pt(size)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def delete_row(row):
    row._tr.getparent().remove(row._tr)


def find_body_index(doc, prefix):
    body = list(doc.element.body)
    for idx, el in enumerate(body):
        if el.tag.rsplit("}", 1)[-1] == "p" and element_text(el).strip().startswith(prefix):
            return idx
    raise ValueError(f"Body element not found: {prefix!r}")


def delete_section(doc, start_prefix, end_prefix):
    body = doc.element.body
    elems = list(body)
    start = find_body_index(doc, start_prefix)
    end = find_body_index(doc, end_prefix)
    for el in elems[start:end]:
        body.remove(el)


def insert_paragraph_before(doc, anchor_el, text="", bold=True, style=None):
    p = doc.add_paragraph()
    if style is not None:
        p.style = style
    run = p.add_run(text)
    run.bold = bold
    anchor_el.addprevious(p._p)
    return p


def insert_table_before(doc, anchor_el, rows, bold=True, font_size=8):
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    try:
        table.style = "Table Grid"
    except Exception:
        pass
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for r_idx, row in enumerate(rows):
        for c_idx, value in enumerate(row):
            set_cell(table.cell(r_idx, c_idx), value, bold=bold, size=font_size)
    anchor_el.addprevious(table._tbl)
    return table


def set_table_data(table, rows, bold=False):
    while len(table.rows) < len(rows):
        table.add_row()
    while len(table.rows) > len(rows):
        delete_row(table.rows[-1])
    for r_idx, row in enumerate(rows):
        cells = table.rows[r_idx].cells
        for c_idx, value in enumerate(row):
            set_cell(cells[c_idx], value, bold=bold)


